// Renders the key registry as a Markdown table (docs/MIGRATION.md).
//   node tools/keys-table.mjs        prints the table
// tests/migration-doc.test.mjs checks that the document contains exactly
// this table, so the document can never drift from the code.
import { REGISTRY } from '../app/core/storage.js';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

export const START = '<!-- keys:start (generated by tools/keys-table.mjs — do not edit by hand) -->';
export const END = '<!-- keys:end -->';

const esc = s => String(s).replace(/\|/g, '\\|');

export function renderTable() {
  const lines = ['| Key | Scope | Since | Cloud merge | Holds |', '|---|---|---|---|---|'];
  for (const e of REGISTRY) {
    const sample = e.build(e.id === 'editorBank' || e.id === 'editorVersion' ? '<module>' : '<P>');
    const flags = [e.writable === false ? 'legacy, read-only' : null, e.secret ? '**secret**' : null].filter(Boolean).join(', ');
    lines.push(`| \`${esc(sample)}\` | ${e.scope}${flags ? ` (${flags})` : ''} | v${e.since} | ${e.sync ? `\`${e.sync}\`` : 'none (device-local)'} | ${esc(e.shape)} |`);
  }
  return lines.join('\n');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log(renderTable());
}
