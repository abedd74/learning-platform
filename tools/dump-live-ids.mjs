// One-off: record the identifiers the OLD app uses as progress keys, so the
// rebuilt app can be tested against them (DESIGN §5.2, "golden file").
//
//   node tools/dump-live-ids.mjs        → tests/fixtures/live-ids.json
//
// Opens the old pages (index.html, grammatik.html, wortregen.html) from this
// checkout on the local server in WebKit, with a fresh, empty browser profile
// (so no editor overrides and no family sync), blocks every request that does
// not go to the local server, and reads from the running pages:
//  - quiz modules: per module and topic, the question ids in bank order
//    (keys of wq_srs_<P> / wq_stats_<P>), the old positional id and the type
//  - the trainer's nouns (keys of gram_srs_<P>), the game's word list,
//    badge ids (keys of gram_badges_<P>) and the Lernpfad courses.
// The file contains identifiers only, no question text.
import { writeFileSync, mkdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { webkit } from 'playwright';
import { startServer } from './serve.mjs';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
const OUT = join(ROOT, 'tests', 'fixtures', 'live-ids.json');

const source = execFileSync('git', ['log', '-1', '--format=%h', '--', 'index.html', 'grammatik.html', 'wortregen.html'],
  { cwd: ROOT }).toString().trim();

const { server, url } = await startServer({ port: 0 });
const browser = await webkit.launch();
const errors = [];

async function open(page, path) {
  page.on('pageerror', e => errors.push(`${path}: ${e.message}`));
  await page.route('**/*', route => {
    const u = new URL(route.request().url());
    return (u.hostname === 'localhost' || u.hostname === '127.0.0.1') ? route.continue() : route.abort();
  });
  await page.goto(url + path, { waitUntil: 'load' });
  await page.waitForTimeout(800);   // let late init (self-heal check, id assignment) settle
}

try {
  const context = await browser.newContext();

  const index = await context.newPage();
  await open(index, 'index.html');
  const quiz = await index.evaluate(() => {
    const out = {};
    for (const [key, m] of Object.entries(EDITOR_MODULES)) {
      if (typeof m.getQB !== 'function') continue;
      const qb = m.getQB();
      const topics = {};
      for (const t of Object.keys(qb)) {
        topics[t] = qb[t].map(q => ({ id: q.id, legacyId: q._legacyId ?? null, type: q.type }));
      }
      out[key] = { idPrefix: m.idPrefix ?? '', storageKey: m.storageKey ?? null, tkeys: m.tkeys ?? Object.keys(qb), topics };
    }
    return out;
  });

  const gram = await context.newPage();
  await open(gram, 'grammatik.html');
  const trainer = await gram.evaluate(() => ({
    nouns: NOUNS.map(n => n.de),
    badges: BADGES.map(b => b.id),
    paths: { akk: PATH_AKK.length, dat: PATH_DAT.length, nomen: PATH_NOMEN.length },
    intervals: INTERVALS,
  }));

  const wr = await context.newPage();
  await open(wr, 'wortregen.html');
  const wordrain = await wr.evaluate(() => WORDS.map(w => w[0]));

  if (errors.length) throw new Error('page errors while loading the old app:\n' + errors.join('\n'));

  const counts = Object.fromEntries(Object.entries(quiz).map(([k, m]) =>
    [k, Object.values(m.topics).reduce((n, list) => n + list.length, 0)]));
  const allIds = Object.values(quiz).flatMap(m => Object.values(m.topics).flat().map(q => q.id));
  const dupes = allIds.filter((id, i) => allIds.indexOf(id) !== i);
  if (dupes.length) throw new Error(`duplicate ids in the live app: ${dupes.join(', ')}`);

  const golden = {
    about: 'Progress-key identifiers of the old app (before the rebuild). Generated by tools/dump-live-ids.mjs; do not edit by hand.',
    source: `commit ${source}`,
    counts: { ...counts, total: allIds.length, nouns: trainer.nouns.length, wordrain: wordrain.length },
    quiz,
    trainer,
    wordrain,
  };
  mkdirSync(join(ROOT, 'tests', 'fixtures'), { recursive: true });
  writeFileSync(OUT, JSON.stringify(golden, null, 1) + '\n');
  console.log(`dump-live-ids: wrote ${OUT.slice(ROOT.length + 1)}`);
  console.log(`  ${JSON.stringify(golden.counts)}`);
} finally {
  await browser.close();
  server.close();
}
